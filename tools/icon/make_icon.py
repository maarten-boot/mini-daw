#!/usr/bin/env python3
"""Draws the mini-daw icon (P9b) and writes it in the formats the build uses.

    python3 tools/icon/make_icon.py

Writes:
  res/mini-daw.ico        Windows icon, 16 to 256 px (program file, installer, window)
  res/mini-daw-256.png    the same at 256 px (README, Linux desktop files later)
  src/app/icon_data.hpp   32 and 48 px RGBA pixels for the window icon on Linux

The design: a white rounded square with a black border, a black waveform
across the middle and a red "record" dot. Black on white, and red #C8102E on
white is 5.9:1, so it stays readable at small sizes and in high contrast.
Needs Pillow (a development tool only; nothing of it is built into mini-daw).
Part of mini-daw, MIT licence.
"""
import math
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
BIG = 1024  # drawn large, then scaled down for every size
RED = (200, 16, 46, 255)
BLACK = (0, 0, 0, 255)
WHITE = (255, 255, 255, 255)


def draw(size: int = BIG, bars: int = 13) -> Image.Image:
    """`bars`: 13 for the large sizes, 7 thicker ones for 32 px and below (stay sharp)."""
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    s = size / 1024.0
    d.rounded_rectangle([32 * s, 32 * s, 992 * s, 992 * s], radius=170 * s, fill=WHITE, outline=BLACK,
                        width=int(56 * s))
    # Waveform: vertical bars following a decaying burst, like a recorded note.
    x0, x1 = 150 * s, 874 * s
    mid = 560 * s
    step = (x1 - x0) / (bars - 1)
    for i in range(bars):
        t = i / (bars - 1)
        amp = (0.15 + 0.85 * math.sin(math.pi * t) * (1.0 - 0.45 * t)) * 300 * s
        x = x0 + i * step
        w = step * (0.55 if bars > 8 else 0.62)
        d.rounded_rectangle([x - w / 2, mid - amp, x + w / 2, mid + amp], radius=w / 2, fill=BLACK)
    # Record dot, top right.
    cx, cy, r = 800 * s, 230 * s, 110 * s
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=RED, outline=WHITE, width=int(24 * s))
    return img


def main() -> None:
    big = draw()
    small = draw(bars=7)
    sizes = [16, 24, 32, 48, 64, 128, 256]
    res = ROOT / "res"
    res.mkdir(exist_ok=True)
    big.resize((256, 256), Image.LANCZOS).save(res / "mini-daw-256.png")
    images = [(small if n <= 32 else big).resize((n, n), Image.LANCZOS) for n in sizes]
    images[-1].save(res / "mini-daw.ico", sizes=[(n, n) for n in sizes], append_images=images[:-1])

    out = ["// Generated by tools/icon/make_icon.py - do not edit.",
           "// The mini-daw window icon (Linux; Windows uses the icon resource).",
           "#pragma once", "", "#include <cstdint>", "", "namespace minidaw::app {", ""]
    for n in (32, 48):
        px = (small if n <= 32 else big).resize((n, n), Image.LANCZOS).tobytes()
        out.append(f"inline constexpr int kIcon{n}Size = {n};")
        out.append(f"inline constexpr std::uint8_t kIcon{n}[] = {{")
        for i in range(0, len(px), 24):
            out.append("    " + ", ".join(str(b) for b in px[i:i + 24]) + ",")
        out.append("};")
        out.append("")
    out.append("} // namespace minidaw::app")
    (ROOT / "src" / "app" / "icon_data.hpp").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote res/mini-daw.ico, res/mini-daw-256.png, src/app/icon_data.hpp")


if __name__ == "__main__":
    main()
